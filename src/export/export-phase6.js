/** Render one offscreen frame at w×h and return the raw ImageData */
function _renderOffscreen(w, h, { alpha = false } = {}) {
  const offCanvas = document.createElement('canvas');
  offCanvas.width = w;
  offCanvas.height = h;

  const offRenderer = new THREE.WebGLRenderer({
    canvas: offCanvas,
    antialias: true,
    alpha,
    preserveDrawingBuffer: true,
  });
  offRenderer.setPixelRatio(1);
  offRenderer.setSize(w, h, false);

  const offMat = new THREE.ShaderMaterial({
    vertexShader: VERT,
    fragmentShader: state.mat3.fragmentShader,
    uniforms: {
      ...state.mat3.uniforms,
      iResolution: { value: new THREE.Vector3(w, h, 1) },
    },
    transparent: alpha,
  });

  const offScene = new THREE.Scene();
  const offCam = new THREE.OrthographicCamera(-1, 1, 1, -1, 0, 1);
  const offMesh = new THREE.Mesh(new THREE.PlaneGeometry(2, 2), offMat);
  offScene.add(offMesh);
  offRenderer.render(offScene, offCam);

  const gl = offRenderer.getContext();
  const buf = new Uint8Array(w * h * 4);
  gl.readPixels(0, 0, w, h, gl.RGBA, gl.UNSIGNED_BYTE, buf);

  // Flip Y (WebGL origin bottom-left → image top-left)
  const flipped = new Uint8ClampedArray(w * h * 4);
  for (let row = 0; row < h; row++) {
    const src = (h - 1 - row) * w * 4;
    flipped.set(buf.subarray(src, src + w * 4), row * w * 4);
  }

  offMesh.geometry.dispose();
  offMat.dispose();
  offRenderer.dispose();

  return new ImageData(flipped, w, h);
}

function _triggerDownload(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

